import threading as _threading
_lang_local = _threading.local()
_default_lang = "es"


def set_lang(lang: str):
    """Thread-safe: cada hilo puede tener su idioma, pero el default es global."""
    global _default_lang
    if lang in TRANSLATIONS:
        _default_lang = lang
        _lang_local.lang = lang


def get_lang() -> str:
    return getattr(_lang_local, "lang", _default_lang)


def t(key: str, **kwargs) -> str:
    """Traduce una clave al idioma actual."""
    text = TRANSLATIONS.get(_current_lang, TRANSLATIONS["es"]).get(key)
    if text is None:
        text = TRANSLATIONS["es"].get(key, key)
    if kwargs:
        try:
            text = text.format(**kwargs)
        except Exception:
            pass
    return text
